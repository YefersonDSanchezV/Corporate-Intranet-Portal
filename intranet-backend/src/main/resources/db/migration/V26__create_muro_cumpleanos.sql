-- V26__create_muro_cumpleanos.sql — Muro de Cumpleaños (bandeja de conversación)
-- Tabla viva con los mensajes del día + histórico archivado por el job nocturno.
-- Idempotente para BDs nuevas y existentes.

CREATE TABLE IF NOT EXISTS genmuromen (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genusuario integer NOT NULL REFERENCES genusuario (oid),
    genmuromentex character varying(500) NOT NULL,
    genmuromenfech timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS genmuromenhist (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genmuromenhautor character varying(255) NOT NULL,
    genmuromenhtex character varying(500) NOT NULL,
    genmuromenhfech timestamp NOT NULL,
    genmuromenhfecharch timestamp NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_muromen_fecha ON genmuromen (genmuromenfech DESC, oid DESC);
CREATE INDEX IF NOT EXISTS idx_muromen_autor ON genmuromen (genusuario);
CREATE INDEX IF NOT EXISTS idx_muromenhist_fecha ON genmuromenhist (genmuromenhfech DESC);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='genmuromen' AND column_name='oid' AND is_identity='YES') THEN
    EXECUTE 'ALTER TABLE genmuromen ALTER COLUMN oid ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='genmuromenhist' AND column_name='oid' AND is_identity='YES') THEN
    EXECUTE 'ALTER TABLE genmuromenhist ALTER COLUMN oid ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;
END $$;

SELECT setval(pg_get_serial_sequence('genmuromen','oid'), GREATEST(1, COALESCE((SELECT MAX(oid) FROM genmuromen),1)), true);
SELECT setval(pg_get_serial_sequence('genmuromenhist','oid'), GREATEST(1, COALESCE((SELECT MAX(oid) FROM genmuromenhist),1)), true);
