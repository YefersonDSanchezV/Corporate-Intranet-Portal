-- V31__create_plantillas_cumpleanios.sql — Plantillas (imágenes) de tarjetas de cumpleaños.
-- Cada plantilla referencia el archivo almacenado por FileService (MinIO o disco local).
-- Idempotente para BDs nuevas y existentes.

CREATE TABLE IF NOT EXISTS genplantillacumple (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genplannombre character varying(120) NOT NULL,
    genarchivo integer NOT NULL REFERENCES genarchivo (oid) ON DELETE CASCADE,
    genplanfechcrea timestamp NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_plantilla_cumple_archivo ON genplantillacumple (genarchivo);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='genplantillacumple' AND column_name='oid' AND is_identity='YES') THEN
    EXECUTE 'ALTER TABLE genplantillacumple ALTER COLUMN oid ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;
END $$;

INSERT INTO genparametro (clave, valor, descripcion, fecha_actualizacion) VALUES
    ('PLANTILLAS_CUMPLE_MAX_MB', '5', 'Tamaño máximo en MB para plantillas de cumpleaños', NOW())
ON CONFLICT (clave) DO NOTHING;
