-- V16__add_cargo_module_permissions.sql — Persistencia de permisos de módulos del panel de control por cargo
-- Soluciona pérdida de permisos al recrear el contenedor docker (antes solo localStorage en frontend).
-- Cada cargo (gencargointra) puede tener múltiples permisos de tipo MODULO o ACCION.

CREATE TABLE IF NOT EXISTS gencargopermiso (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gencargointra integer NOT NULL REFERENCES gencargointra(oid) ON DELETE CASCADE,
    permiso character varying(255) NOT NULL,
    tipo character varying(20) NOT NULL CHECK (tipo IN ('MODULO','ACCION')),
    CONSTRAINT uq_cargo_permiso_tipo UNIQUE (gencargointra, permiso, tipo)
);

CREATE INDEX IF NOT EXISTS idx_cargopermiso_cargo ON gencargopermiso(gencargointra);
CREATE INDEX IF NOT EXISTS idx_cargopermiso_tipo ON gencargopermiso(tipo);
