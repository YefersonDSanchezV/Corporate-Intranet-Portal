-- V35__carpetas_almacen.sql — Catálogo dinámico de carpetas de almacenamiento.
--
-- Separa los buckets FÍSICOS de MinIO (pocos: fotos-cumpleanos, documentos, videos)
-- de las carpetas LÓGICAS de negocio (prefijos de objeto dentro del bucket). Así se
-- pueden crear nuevas categorías desde la interfaz sin tocar código ni crear buckets.
--
-- Idempotente: puede ejecutarse sobre una BD que ya tenga V33 y V34 aplicadas sin
-- duplicar registros ni alterar los archivos existentes.

CREATE TABLE IF NOT EXISTS gencarpetaalmacen (
    oid                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gencarpnombre      character varying(120) NOT NULL,
    gencarpdescripcion character varying(255),
    gencarptipo        character varying(20) NOT NULL DEFAULT 'OTROS',
    gencarpbucket      character varying(120) NOT NULL,
    gencarpprefijo     character varying(255) NOT NULL,
    gencarpactivo      boolean NOT NULL DEFAULT true,
    gencarpfechcrea    timestamp NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_carpeta_bucket_prefijo UNIQUE (gencarpbucket, gencarpprefijo)
);

CREATE INDEX IF NOT EXISTS idx_carpeta_almacen_activo ON gencarpetaalmacen (gencarpactivo);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_name='gencarpetaalmacen' AND column_name='oid' AND is_identity='YES') THEN
    EXECUTE 'ALTER TABLE gencarpetaalmacen ALTER COLUMN oid ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Semilla a partir de la configuración existente (parámetros de V29).
-- Se conservan los valores reales de cada parámetro; si no existen se usa el
-- valor por defecto histórico. El prefijo de fotos-cumpleanos es 'cumpleanos/'
-- para mantener EXACTAMENTE las rutas de los archivos ya almacenados.
-- ---------------------------------------------------------------------------

-- Carpetas migradas desde los parámetros antiguos de buckets (VIDEO_BUCKET /
-- DOCS_BUCKET), que hasta ahora ningún flujo leía.
INSERT INTO gencarpetaalmacen (gencarpnombre, gencarpdescripcion, gencarptipo, gencarpbucket, gencarpprefijo)
SELECT 'documentos', 'Documentos y formatos del portal', 'DOCUMENTOS',
       COALESCE(NULLIF((SELECT valor FROM genparametro WHERE clave = 'DOCS_BUCKET'), ''), 'documentos'),
       'documentos/'
WHERE NOT EXISTS (
    SELECT 1 FROM gencarpetaalmacen c
    WHERE c.gencarpbucket = COALESCE(NULLIF((SELECT valor FROM genparametro WHERE clave = 'DOCS_BUCKET'), ''), 'documentos')
      AND c.gencarpprefijo = 'documentos/'
);

INSERT INTO gencarpetaalmacen (gencarpnombre, gencarpdescripcion, gencarptipo, gencarpbucket, gencarpprefijo)
SELECT 'videos', 'Material audiovisual del portal', 'VIDEOS',
       COALESCE(NULLIF((SELECT valor FROM genparametro WHERE clave = 'VIDEO_BUCKET'), ''), 'videos'),
       'videos/'
WHERE NOT EXISTS (
    SELECT 1 FROM gencarpetaalmacen c
    WHERE c.gencarpbucket = COALESCE(NULLIF((SELECT valor FROM genparametro WHERE clave = 'VIDEO_BUCKET'), ''), 'videos')
      AND c.gencarpprefijo = 'videos/'
);

-- Carpeta por defecto de fotos de cumpleaños: mismo bucket y mismo prefijo que
-- usa hoy FileService.store(), de modo que los archivos nuevos caigan donde
-- siempre y los antiguos sigan siendo alcanzables por su misma ruta.
INSERT INTO gencarpetaalmacen (gencarpnombre, gencarpdescripcion, gencarptipo, gencarpbucket, gencarpprefijo)
SELECT 'fotos-cumpleanos', 'Fotos de los cumpleaños del portal', 'IMAGENES',
       COALESCE(NULLIF((SELECT valor FROM genparametro WHERE clave = 'FOTOS_CUMPLE_BUCKET'), ''), 'fotos-cumpleanos'),
       'cumpleanos/'
WHERE NOT EXISTS (
    SELECT 1 FROM gencarpetaalmacen c
    WHERE c.gencarpbucket = COALESCE(NULLIF((SELECT valor FROM genparametro WHERE clave = 'FOTOS_CUMPLE_BUCKET'), ''), 'fotos-cumpleanos')
      AND c.gencarpprefijo = 'cumpleanos/'
);

