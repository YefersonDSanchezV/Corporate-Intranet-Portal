-- V27__create_muro_csv.sql — Registro de los CSV generados al cierre del día
-- del Muro de Cumpleaños. Un registro por día (fecha única).
-- Idempotente para BDs nuevas y existentes.

CREATE TABLE IF NOT EXISTS genmurocsv (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genmurocsvfech date NOT NULL UNIQUE,
    genarchivo integer NOT NULL REFERENCES genarchivo (oid),
    genmurocsvtot integer NOT NULL,
    genmurocsvfechcre timestamp NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_murocsv_fecha ON genmurocsv (genmurocsvfech DESC);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='genmurocsv' AND column_name='oid' AND is_identity='YES') THEN
    EXECUTE 'ALTER TABLE genmurocsv ALTER COLUMN oid ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;
END $$;

SELECT setval(pg_get_serial_sequence('genmurocsv','oid'), GREATEST(1, COALESCE((SELECT MAX(oid) FROM genmurocsv),1)), true);
