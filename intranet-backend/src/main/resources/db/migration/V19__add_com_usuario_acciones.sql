CREATE TABLE IF NOT EXISTS comusuario_accion (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genusuario integer NOT NULL REFERENCES genusuario(oid) ON DELETE CASCADE,
    accion character varying(255) NOT NULL,
    CONSTRAINT uq_usuario_accion UNIQUE (genusuario, accion)
);
CREATE INDEX IF NOT EXISTS idx_comusuario_accion_usuario ON comusuario_accion(genusuario);
