-- V32__cumpleanios_usuario_plantilla.sql — Datos de cumpleaños de usuarios del sistema.
-- Los cumpleaños automáticos se derivan de genusuario (fecha de nacimiento validada).
-- Aquí se guarda sólo lo que el operador configura sobre ellos: la foto de la tarjeta
-- y la plantilla (imagen de fondo) con la posición de la foto en porcentaje.
-- El nombre no sigue la convención "genusufoto_*" a propósito: estas columnas no deben
-- viajar en las instantáneas de usuario (no son datos de autenticación).

-- Posición y tamaño de la foto del funcionario sobre la plantilla, en porcentaje (0-100).
-- V31 ya está aplicada en los ambientes existentes, por eso las columnas se agregan aquí.
ALTER TABLE genplantillacumple ADD COLUMN IF NOT EXISTS genplanfotopx numeric(6,3) NOT NULL DEFAULT 50;
ALTER TABLE genplantillacumple ADD COLUMN IF NOT EXISTS genplanfotopy numeric(6,3) NOT NULL DEFAULT 34;
ALTER TABLE genplantillacumple ADD COLUMN IF NOT EXISTS genplanfotowancho numeric(6,3) NOT NULL DEFAULT 26;
ALTER TABLE genplantillacumple ADD COLUMN IF NOT EXISTS genplanfotoalto numeric(6,3) NOT NULL DEFAULT 26;
ALTER TABLE genplantillacumple ADD COLUMN IF NOT EXISTS genplanfotoredondo boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS genusucumple (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genusuario integer NOT NULL REFERENCES genusuario (oid) ON DELETE CASCADE,
    genucumfoto integer REFERENCES genarchivo (oid) ON DELETE SET NULL,
    genucumplantilla integer REFERENCES genplantillacumple (oid) ON DELETE SET NULL,
    genucumfechact timestamp NOT NULL
);

-- Un único registro de configuración por usuario.
CREATE UNIQUE INDEX IF NOT EXISTS uq_usucumple_usuario ON genusucumple (genusuario);

-- Posición y tamaño de la foto en porcentaje (0-100) sobre la plantilla.
ALTER TABLE genusucumple ADD COLUMN IF NOT EXISTS genucumfotopx numeric(6,3) NOT NULL DEFAULT 50;
ALTER TABLE genusucumple ADD COLUMN IF NOT EXISTS genucumfotopy numeric(6,3) NOT NULL DEFAULT 34;
ALTER TABLE genusucumple ADD COLUMN IF NOT EXISTS genucumfotowancho numeric(6,3) NOT NULL DEFAULT 26;
ALTER TABLE genusucumple ADD COLUMN IF NOT EXISTS genucumfotoalto numeric(6,3) NOT NULL DEFAULT 26;
ALTER TABLE genusucumple ADD COLUMN IF NOT EXISTS genucumfotoredondo boolean NOT NULL DEFAULT true;

CREATE INDEX IF NOT EXISTS idx_usucumple_usuario ON genusucumple (genusuario);
CREATE INDEX IF NOT EXISTS idx_usucumple_plantilla ON genusucumple (genucumplantilla);

-- Cumpleaños manuales: plantilla asignada, posición de la foto en porcentaje (0-100)
-- sobre la plantilla y marca de última actualización.
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumplantilla integer REFERENCES genplantillacumple (oid) ON DELETE SET NULL;
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumfotopx numeric(6,3) NOT NULL DEFAULT 50;
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumfotopy numeric(6,3) NOT NULL DEFAULT 34;
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumfotowancho numeric(6,3) NOT NULL DEFAULT 26;
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumfotoalto numeric(6,3) NOT NULL DEFAULT 26;
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumfotoredondo boolean NOT NULL DEFAULT true;
ALTER TABLE gencumpleanos ADD COLUMN IF NOT EXISTS gencumfechact timestamp;

CREATE INDEX IF NOT EXISTS idx_cumpleanos_plantilla ON gencumpleanos (gencumplantilla);

