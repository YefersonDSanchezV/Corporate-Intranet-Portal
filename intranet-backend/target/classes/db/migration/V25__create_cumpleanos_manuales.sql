-- V25__create_cumpleanos_manuales.sql — Cumpleaños registrados manualmente
-- (botón "Nuevo cumpleaños"). El cargo es texto libre escrito por el operador,
-- independiente del catálogo gencargointra.
-- Idempotente para BDs nuevas y existentes.

CREATE TABLE IF NOT EXISTS gencumpleanos (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gencumnomcom character varying(255) NOT NULL,
    gencumfecnam date NOT NULL,
    gencumcargo character varying(255) NOT NULL,
    gencumfechcrea timestamp NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cumpleanos_nombre ON gencumpleanos (gencumnomcom);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gencumpleanos' AND column_name='oid' AND is_identity='YES') THEN
    EXECUTE 'ALTER TABLE gencumpleanos ALTER COLUMN oid ADD GENERATED BY DEFAULT AS IDENTITY';
  END IF;
END $$;

SELECT setval(pg_get_serial_sequence('gencumpleanos','oid'), GREATEST(1, COALESCE((SELECT MAX(oid) FROM gencumpleanos),1)), true);
