-- =============================================================================
-- V1__baseline.sql — Esquema base completo de la Intranet Institucional
-- =============================================================================
-- Reescritura de la migración baseline (antes solo comentarios).
-- Para la BD real (ya con esquema y flyway_schema_history) NO se vuelve a
-- ejecutar: application-*.yml usa flyway.baseline-on-migrate=true + baseline-version=1.
-- Para entornos nuevos, este script crea el esquema desde cero.
--
-- Referencia de esquema: docs/DATABASE.md (29 tablas, dominios asi-/com-/gen-/innov-).
-- Convenciones: PK siempre `oid integer`; FK = nombre de la tabla padre
-- (excepción: gensitredireccion.modulo -> genmodulo).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Tipos enumerados (USER-DEFINED) usados por las columnas de estado.
--    Nombres en mayúsculas con comillas para coincidir con los enums Java
--    (EstadoAnuncio, EstadoTarea, PrioridadTarea, EstadoSolicitud).
-- -----------------------------------------------------------------------------
CREATE TYPE "EstadoAnuncio" AS ENUM ('PENDIENTE', 'PUBLICADO', 'RECHAZADO', 'VENCIDO');
CREATE TYPE "EstadoTarea" AS ENUM ('PENDIENTE', 'EN_PROGRESO', 'COMPLETADA');
CREATE TYPE "PrioridadTarea" AS ENUM ('ALTA', 'MEDIA', 'BAJA');
CREATE TYPE "EstadoSolicitud" AS ENUM ('PENDIENTE', 'APROBADA', 'RECHAZADA');

-- -----------------------------------------------------------------------------
-- 2. Tablas base sin dependencias
-- -----------------------------------------------------------------------------

CREATE TABLE genarea (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genareanom character varying(255) NOT NULL
);

CREATE TABLE genpiso (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genpisnom character varying(255) NOT NULL
);

CREATE TABLE gencargointra (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gencarnom character varying(255) NOT NULL,
    gencaresta boolean NOT NULL
);

CREATE TABLE genmodulo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genmodnom character varying(255) NOT NULL,
    genmodest boolean NOT NULL
);

CREATE TABLE genequipodominio (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geneqnombre character varying(255) NOT NULL,
    genequiou character varying(255),
    geneqactivo boolean NOT NULL,
    genequltsyn timestamp
);

CREATE TABLE asiconextern (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiconextnomsi character varying(255) NOT NULL,
    asiconexturlsi character varying(255) NOT NULL
);

CREATE TABLE comtipoanuncio (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comtipnom character varying(255) NOT NULL
);

CREATE TABLE comrol (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comrolnom character varying(255) NOT NULL,
    comroldes text
);

CREATE TABLE compermisos (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compernom character varying(255) NOT NULL,
    comperdes character varying(255)
);

-- -----------------------------------------------------------------------------
-- 3. Usuarios y tablas que dependen de las base
-- -----------------------------------------------------------------------------

CREATE TABLE genusuario (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genusunom character varying(255) NOT NULL,
    genusuclahash character varying(255) NOT NULL,
    genususta boolean NOT NULL,
    genusuide bigint NOT NULL,
    genusunomcom character varying(255) NOT NULL,
    genusufecnam date NOT NULL,
    genusuemacor character varying(255) NOT NULL,
    gencargointra integer NOT NULL REFERENCES gencargointra (oid),
    genusufechcrea timestamp NOT NULL
);

CREATE TABLE genarchivo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genarchnom character varying(255) NOT NULL,
    genarchnomori character varying(255) NOT NULL,
    genarchruta character varying(500) NOT NULL,
    genarchtipo character varying(255),
    genarchsize bigint,
    genarchfechcre timestamp NOT NULL,
    genusuario integer NOT NULL REFERENCES genusuario (oid)
);

CREATE TABLE gendircextenciones (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gendirextnom character varying(255) NOT NULL,
    gendirext integer NOT NULL,
    gendirextare integer NOT NULL REFERENCES genarea (oid),
    gendirextpis integer NOT NULL REFERENCES genpiso (oid),
    gendirextsop boolean NOT NULL
);

CREATE TABLE gendircorreo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gendircornom character varying(255) NOT NULL,
    gendircor character varying(255) NOT NULL,
    gendircorare integer NOT NULL REFERENCES genarea (oid),
    gendircorpis integer NOT NULL REFERENCES genpiso (oid),
    gendircorsop boolean NOT NULL
);

CREATE TABLE gensitredireccion (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gensitrednom character varying(255) NOT NULL,
    gensitredurl character varying(255) NOT NULL,
    modulo integer NOT NULL REFERENCES genmodulo (oid),
    gensitredicon character varying(255) NOT NULL
);

CREATE TABLE gensolusuario (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gensolusuiden bigint NOT NULL,
    gensolusunomb character varying(255) NOT NULL,
    gensolusucarg character varying(255) NOT NULL,
    gensolusumail character varying(255) NOT NULL,
    gensolusuesta "EstadoSolicitud" NOT NULL,
    gensolfechsol timestamp NOT NULL,
    gensolfechapr timestamp,
    gensolfechrech timestamp,
    gensolusuobse text NOT NULL
);

CREATE TABLE genlogs (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genusuario integer NOT NULL REFERENCES genusuario (oid),
    genlogacci character varying(255),
    genlogvalant text,
    genlogvalnue text,
    genlogfechac timestamp NOT NULL,
    genlogip character varying(255),
    genlogtabla character varying(255),
    genlogregist text
);

-- -----------------------------------------------------------------------------
-- 4. Comunicaciones
-- -----------------------------------------------------------------------------

CREATE TABLE comrolpermiso (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comrol integer NOT NULL REFERENCES comrol (oid),
    compermisos integer NOT NULL REFERENCES compermisos (oid)
);

CREATE TABLE comusuario (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genusuario integer NOT NULL REFERENCES genusuario (oid),
    comrol integer NOT NULL REFERENCES comrol (oid),
    comusuestado boolean NOT NULL
);

CREATE TABLE comtarsegui (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comtarsetit character varying(255) NOT NULL,
    comtarsedes character varying(255),
    comusuarioasig integer NOT NULL REFERENCES comusuario (oid),
    comusuarioqasig integer NOT NULL REFERENCES comusuario (oid),
    comtarestad "EstadoTarea" NOT NULL,
    comtarfechin timestamp,
    comtarfechli timestamp,
    comtarprior "PrioridadTarea" NOT NULL
);

CREATE TABLE comtarcome (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comtarsegui integer NOT NULL REFERENCES comtarsegui (oid),
    comtarcomdes character varying(255),
    comtarcomfec timestamp NOT NULL,
    genusuario integer NOT NULL REFERENCES genusuario (oid)
);

CREATE TABLE comanuncio (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanutit character varying(255) NOT NULL,
    comanudes text NOT NULL,
    comanutipo integer NOT NULL REFERENCES comtipoanuncio (oid),
    comanufechini timestamp,
    comanufechfin timestamp,
    comusuario integer REFERENCES comusuario (oid),
    comanuestado "EstadoAnuncio" NOT NULL,
    comanufechcre timestamp NOT NULL,
    comanuvigenci timestamp,
    comanueliminado boolean NOT NULL
);

CREATE TABLE comlogroacredi (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comlogacretitu character varying(255) NOT NULL,
    comlogacredesc character varying(255),
    comlogacreurlima character varying(255),
    comlogacrefechacre timestamp NOT NULL
);

CREATE TABLE comanuncioarchivo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanuncio integer NOT NULL REFERENCES comanuncio (oid),
    genarchivo integer NOT NULL REFERENCES genarchivo (oid)
);

CREATE TABLE comtareaarchivo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comtarsegui integer NOT NULL REFERENCES comtarsegui (oid),
    genarchivo integer NOT NULL REFERENCES genarchivo (oid)
);

CREATE TABLE comlogroarchivo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comlogroacredi integer NOT NULL REFERENCES comlogroacredi (oid),
    genarchivo integer NOT NULL REFERENCES genarchivo (oid)
);

-- -----------------------------------------------------------------------------
-- 5. Asistencial (formatos y archivos)
-- -----------------------------------------------------------------------------

CREATE TABLE asiforcontin (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiforconnomfor character varying(255) NOT NULL,
    asiforconobserv character varying(255),
    asiforconcodigo character varying(255)
);

CREATE TABLE asiforconarchivo (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiforcontin integer NOT NULL REFERENCES asiforcontin (oid),
    genarchivo integer NOT NULL REFERENCES genarchivo (oid)
);

-- -----------------------------------------------------------------------------
-- 6. Innovación y analítica
-- -----------------------------------------------------------------------------

CREATE TABLE innovanalitica (
    oid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    innovanalinom character varying(255) NOT NULL,
    innovanaliurl character varying(255) NOT NULL,
    genusuario integer NOT NULL REFERENCES genusuario (oid),
    innovanalifechcrea timestamp NOT NULL
);

-- -----------------------------------------------------------------------------
-- 7. Índices sobre columnas foráneas y de consulta frecuente
-- -----------------------------------------------------------------------------

CREATE INDEX idx_usuario_username ON genusuario (genusunom);
CREATE INDEX idx_usuario_correo ON genusuario (genusuemacor);
CREATE INDEX idx_usuario_cargo ON genusuario (gencargointra);

CREATE INDEX idx_archivo_usuario ON genarchivo (genusuario);
CREATE INDEX idx_logs_usuario ON genlogs (genusuario);
CREATE INDEX idx_logs_fecha ON genlogs (genlogfechac);
CREATE INDEX idx_solicitud_estado ON gensolusuario (gensolusuesta);

CREATE INDEX idx_dir_ext_area ON gendircextenciones (gendirextare);
CREATE INDEX idx_dir_ext_piso ON gendircextenciones (gendirextpis);
CREATE INDEX idx_dir_cor_area ON gendircorreo (gendircorare);
CREATE INDEX idx_dir_cor_piso ON gendircorreo (gendircorpis);

CREATE INDEX idx_sitio_modulo ON gensitredireccion (modulo);

CREATE INDEX idx_anuncio_estado ON comanuncio (comanuestado);
CREATE INDEX idx_anuncio_tipo ON comanuncio (comanutipo);
