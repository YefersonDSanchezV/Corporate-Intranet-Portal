CREATE INDEX idx_tarea_asignado ON comtarsegui (comusuarioasig);
CREATE INDEX idx_tarea_estado ON comtarsegui (comtarestad);
CREATE INDEX idx_tarea_prioridad ON comtarsegui (comtarprior);
CREATE INDEX idx_comentario_tarea ON comtarcome (comtarsegui);

CREATE INDEX idx_anuncio_archivo ON comanuncioarchivo (comanuncio);
CREATE INDEX idx_anuncio_archivo_arch ON comanuncioarchivo (genarchivo);
CREATE INDEX idx_tarea_archivo ON comtareaarchivo (comtarsegui);
CREATE INDEX idx_tarea_archivo_arch ON comtareaarchivo (genarchivo);
CREATE INDEX idx_logro_archivo ON comlogroarchivo (comlogroacredi);
CREATE INDEX idx_logro_archivo_arch ON comlogroarchivo (genarchivo);

CREATE INDEX idx_formato_archivo ON asiforconarchivo (asiforcontin);
CREATE INDEX idx_formato_archivo_arch ON asiforconarchivo (genarchivo);

CREATE INDEX idx_innov_usuario ON innovanalitica (genusuario);